/**
 * Generates mobile/src/app/version.ts and the iOS version settings from config/app_version.json.
 * `npm run version:bundle`. Android reads the JSON directly in app/build.gradle. A test fails if the
 * outputs are stale or the build number does not increase.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export interface VersionJson {
  version: string;
  build_number: number;
  history: { build_number: number; version: string; task: string; commit: string; label: string; apk_sha256: string | null; apk_sha256_arm64?: string; note: string }[];
}

export function readVersion(root = ROOT): VersionJson {
  const v = JSON.parse(readFileSync(join(root, 'config', 'app_version.json'), 'utf8')) as VersionJson;
  const problems: string[] = [];
  if (!/^\d+\.\d+\.\d+$/.test(v.version)) problems.push('version must be MAJOR.MINOR.PATCH');
  if (!Number.isInteger(v.build_number) || v.build_number < 1 || v.build_number > 2_100_000_000) problems.push('build_number must be a positive integer');
  const builds = v.history.map((h) => h.build_number);
  if (new Set(builds).size !== builds.length) problems.push('history build numbers must be unique');
  if (Math.max(...builds) !== v.build_number) problems.push('build_number must be the highest build in history');
  const current = v.history.find((h) => h.build_number === v.build_number);
  if (!current || current.version !== v.version) problems.push('history must contain the current build with the current version');
  if (problems.length) throw new Error(`config/app_version.json: ${problems.join('; ')}`);
  return v;
}

export function buildVersionModule(v = readVersion()): string {
  return `/** GENERATED by scripts/bundle_version.ts from config/app_version.json — do not edit. */
export const APP_VERSION = ${JSON.stringify(v.version)};
export const BUILD_NUMBER = ${v.build_number};
`;
}

/** Set MARKETING_VERSION and CURRENT_PROJECT_VERSION in the iOS project. */
export function withIosVersion(pbxproj: string, v: VersionJson): string {
  return pbxproj.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${v.version};`).replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${v.build_number};`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const v = readVersion();
  writeFileSync(join(ROOT, 'mobile', 'src', 'app', 'version.ts'), buildVersionModule(v));
  const p = join(ROOT, 'mobile', 'ios', 'RxRecallCheck.xcodeproj', 'project.pbxproj');
  writeFileSync(p, withIosVersion(readFileSync(p, 'utf8'), v));
  console.log(`version ${v.version} (build ${v.build_number}) → mobile/src/app/version.ts, iOS project`);
}
