/**
 * Bundle docs/legal/*.md into mobile/src/legal/documents.ts so the app shows exactly the reviewed
 * text, with its version and status. Run after editing a legal document:
 *
 *   npm run legal:bundle
 *
 * `tests/unit/claims_and_copy.test.ts` fails if the bundle is out of date.
 *
 * The product name is not written into the documents: they say {{PRODUCT_NAME}}, which is replaced
 * here from config/brand.json (Task 4A.1), so a rename never edits reviewed legal text by hand.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readBrand } from './bundle_brand.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'docs', 'legal');
const OUT = join(ROOT, 'mobile', 'src', 'legal', 'documents.ts');
const FIRST_LAUNCH = new Set(['terms', 'privacy', 'medical']);
const ORDER = ['terms', 'privacy', 'medical', 'sources', 'pilot'];

export function buildLegalBundle(): string {
  const productName = readBrand(ROOT).product_name;
  const docs = readdirSync(DIR)
    .filter((f) => f.endsWith('.md'))
    .map((file) => {
      const source = readFileSync(join(DIR, file), 'utf8');
      if (/Rx Recall Check|MedLuma/.test(source)) throw new Error(`${file}: write {{PRODUCT_NAME}} instead of a product name`);
      const text = source.split('{{PRODUCT_NAME}}').join(productName);
      const field = (name: string) => {
        const m = new RegExp(`^${name}: (.+)$`, 'm').exec(text);
        if (!m) throw new Error(`${file}: missing "${name}:" header`);
        return (m[1] as string).trim();
      };
      const title = (/^# (.+)$/m.exec(text)?.[1] ?? file).trim();
      const status = field('Status');
      return { id: field('Document ID'), title, version: field('Version'), status: status.startsWith('APPROVED') ? 'APPROVED' : 'DRAFT', file: `docs/legal/${file}`, text };
    })
    .sort((a, b) => ORDER.indexOf(a.id) - ORDER.indexOf(b.id));
  const body = docs
    .map((d) => `  { id: ${JSON.stringify(d.id)}, title: ${JSON.stringify(d.title)}, version: ${JSON.stringify(d.version)}, status: ${JSON.stringify(d.status)}, showAtFirstLaunch: ${FIRST_LAUNCH.has(d.id)}, source: ${JSON.stringify(d.file)}, text: ${JSON.stringify(d.text)} },`)
    .join('\n');
  return `/**
 * GENERATED by scripts/bundle_legal_docs.ts from docs/legal/*.md — do not edit by hand.
 * Run \`npm run legal:bundle\` after changing a legal document.
 */
export type LegalDocumentId = ${docs.map((d) => JSON.stringify(d.id)).join(' | ')};

export interface LegalDocument {
  id: LegalDocumentId;
  title: string;
  version: string;
  status: 'DRAFT' | 'APPROVED';
  showAtFirstLaunch: boolean;
  source: string;
  text: string;
}

export const LEGAL_DOCUMENTS: readonly LegalDocument[] = [
${body}
];
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, buildLegalBundle());
  console.log(`wrote ${OUT}`);
}
