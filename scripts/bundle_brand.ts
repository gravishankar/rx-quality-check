/**
 * Generates mobile/src/brand/brand.ts and the iOS display name from config/brand.json (the single
 * source of product identity). `npm run brand:bundle`. A test fails if the outputs are stale.
 *
 * The brand is presentation only: it never affects drug data, exclusion policy, the workflow or the
 * evidence rules, and it never changes package identifiers or signing identities.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export interface BrandJson {
  schema: number;
  product_name: string;
  name_status: string;
  name_status_note: string;
  tagline: string;
  features: Record<string, { name: string; status: string }>;
  app_version: string;
  legal_entity: string;
  display_labels: { development: string; pilot: string };
  audience: { initial: string; future_candidate: string };
  former_names: string[];
  unchanged_identifiers: { android_application_id: string; ios_bundle_id: string; repository: string };
}

const NAME_STATUSES = ['PROVISIONAL_PENDING_CLEARANCE', 'PROVISIONAL_CONFLICTS_FOUND', 'CLEARED_BY_COUNSEL'];

export function readBrand(root = ROOT): BrandJson {
  const b = JSON.parse(readFileSync(join(root, 'config', 'brand.json'), 'utf8')) as BrandJson;
  const problems: string[] = [];
  if (b.schema !== 1) problems.push('schema must be 1');
  for (const k of ['product_name', 'tagline', 'app_version', 'legal_entity'] as const) if (typeof b[k] !== 'string' || b[k].trim() === '') problems.push(`${k} is required`);
  if (!NAME_STATUSES.includes(b.name_status)) problems.push(`name_status must be one of ${NAME_STATUSES.join(', ')}`);
  if (!/^\d+\.\d+\.\d+$/.test(b.app_version)) problems.push('app_version must be MAJOR.MINOR.PATCH');
  if (!b.features?.recall_check?.name) problems.push('features.recall_check.name is required');
  if (!b.display_labels?.development?.includes('DEV')) problems.push('display_labels.development must contain "DEV"');
  if (b.display_labels?.pilot?.includes('DEV')) problems.push('display_labels.pilot must not contain "DEV"');
  if (problems.length) throw new Error(`config/brand.json: ${problems.join('; ')}`);
  return b;
}

export function buildBrandModule(b = readBrand()): string {
  const brand = {
    productName: b.product_name,
    nameStatus: b.name_status,
    tagline: b.tagline,
    features: { recallCheck: b.features.recall_check!.name },
    appVersion: b.app_version,
    legalEntity: b.legal_entity,
    displayLabels: b.display_labels,
  };
  return `/**
 * GENERATED by scripts/bundle_brand.ts from config/brand.json — do not edit.
 * Product identity for screens and copy. Presentation only: no workflow, evidence or data logic
 * depends on it. The name is provisional (see docs/BRAND_CLEARANCE.md).
 */
export type BrandNameStatus = ${NAME_STATUSES.map((s) => `'${s}'`).join(' | ')};

export interface Brand {
  productName: string;
  nameStatus: BrandNameStatus;
  tagline: string;
  features: { recallCheck: string };
  appVersion: string;
  legalEntity: string;
  displayLabels: { development: string; pilot: string };
}

export const BRAND: Brand = ${JSON.stringify(brand, null, 2)};
`;
}

/** Replace CFBundleDisplayName in the iOS Info.plist. */
export function withIosDisplayName(plist: string, name: string): string {
  return plist.replace(/(<key>CFBundleDisplayName<\/key>\s*<string>)[^<]*(<\/string>)/, `$1${name}$2`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const b = readBrand();
  writeFileSync(join(ROOT, 'mobile', 'src', 'brand', 'brand.ts'), buildBrandModule(b));
  const plistPath = join(ROOT, 'mobile', 'ios', 'RxRecallCheck', 'Info.plist');
  writeFileSync(plistPath, withIosDisplayName(readFileSync(plistPath, 'utf8'), b.display_labels.pilot));
  console.log(`brand: ${b.product_name} (${b.name_status}) → mobile/src/brand/brand.ts, iOS display name`);
}
